//! Literal port of `src/mkinit.c`.
//! Rules: `docs/spec/port/src/mkinit.md`.
//!
//! This program scans all the source files for code to handle various
//! special events and combines this code into one file.  This (allegedly)
//! improves the structure of the program since there is no need for
//! anyone outside of a module to know that that module performs special
//! operations on particular events.
//!
//! Usage:  mkinit sourcefile...
//!
//! It is a build-time code generator, not part of the shell; it is ported so
//! that `init.c` stays derivable.  The port keeps the C's globals, `char *`
//! buffers and block lists, so it is `unsafe` throughout.  `match` is spelled
//! `r#match` and `error` takes a `&str`; everything else keeps its name.

use core::ptr;

use libc::{c_char, c_int, c_void, FILE};

/*
 * OUTFILE is the name of the output file.  Output is initially written
 * to the file OUTTEMP, which is then moved to OUTFILE.
 */

static OUTFILE: &core::ffi::CStr = c"init.c";
static OUTTEMP: &core::ffi::CStr = c"init.c.new";

/*
 * A text structure is basicly just a string that grows as more characters
 * are added onto the end of it.  It is implemented as a linked list of
 * blocks of characters.  The routines addstr and addchar append a string
 * or a single character, respectively, to a text structure.  Writetext
 * writes the contents of a text structure to a file.
 */

const BLOCKSIZE: usize = 512;

// [spec:dash:def:mkinit.text]
struct text {
    nextc: *mut c_char,
    nleft: c_int,
    start: *mut block,
    last: *mut block,
}

const TEXT_INIT: text = text {
    nextc: ptr::null_mut(),
    nleft: 0,
    start: ptr::null_mut(),
    last: ptr::null_mut(),
};

// [spec:dash:def:mkinit.block]
struct block {
    next: *mut block,
    text: [c_char; BLOCKSIZE],
}

// [spec:dash:def:mkinit.event]
/// There is one event structure for each event that mkinit handles.
struct event {
    name: &'static core::ffi::CStr,    /* name of event (e.g. INIT) */
    routine: &'static core::ffi::CStr, /* name of routine called on event */
    comment: &'static core::ffi::CStr, /* comment describing routine */
    args: Option<&'static core::ffi::CStr>, /* arguments to routine */
    code: text,                        /* code for handling event */
}

static writer: &core::ffi::CStr =
    c"/*\n * This file was generated by the mkinit program.\n */\n\n";

static init: &core::ffi::CStr = c"/*\n * Initialization code.\n */\n";

static exitreset: &core::ffi::CStr = c"/*\n * This routine is called when an error or an interrupt occurs in an\n * interactive shell and control is returned to the main command loop\n * but prior to exitshell. \n */\n";

static forkreset: &core::ffi::CStr =
    c"/*\n * This routine is called when we enter a subshell.\n */\n";

static postexitreset: &core::ffi::CStr =
    c"/*\n * This routine is called in exitshell.\n */\n";

static reset: &core::ffi::CStr = c"/*\n * This routine is called when an error or an interrupt occurs in an\n * interactive shell and control is returned to the main command loop.\n */\n";

/// The C array ends with a `{NULL, NULL}` sentinel and every loop stops on
/// `ep->name`; the Rust array carries its own length, so the sentinel is
/// dropped and the loops run to `NEVENTS` instead.
const NEVENTS: usize = 5;

static mut event: [event; NEVENTS] = [
    event {
        name: c"INIT",
        routine: c"init",
        comment: init,
        args: None,
        code: TEXT_INIT,
    },
    event {
        name: c"EXITRESET",
        routine: c"exitreset",
        comment: exitreset,
        args: None,
        code: TEXT_INIT,
    },
    event {
        name: c"FORKRESET",
        routine: c"forkreset",
        comment: forkreset,
        args: Some(c"union node *n"),
        code: TEXT_INIT,
    },
    event {
        name: c"POSTEXITRESET",
        routine: c"postexitreset",
        comment: postexitreset,
        args: None,
        code: TEXT_INIT,
    },
    event {
        name: c"RESET",
        routine: c"reset",
        comment: reset,
        args: None,
        code: TEXT_INIT,
    },
];

static mut curfile: *const c_char = ptr::null(); /* current file */
static mut linno: c_int = 0; /* current line */
static mut header_files: [*const c_char; 200] = [ptr::null(); 200]; /* list of header files */
static mut defines: text = TEXT_INIT; /* #define statements */
static mut decls: text = TEXT_INIT; /* declarations */
static mut amiddecls: c_int = 0; /* for formatting */

/// `#define equal(s1, s2)	(strcmp(s1, s2) == 0)`
unsafe fn equal(s1: *const c_char, s2: *const c_char) -> bool {
    libc::strcmp(s1, s2) == 0
}

// [spec:dash:def:mkinit.main-fn]
// [spec:dash:sem:mkinit.main-fn]
pub fn main_fn(_argc: c_int, argv: Vec<String>) -> c_int {
    unsafe {
        header_files[0] = c"\"shell.h\"".as_ptr();
        header_files[1] = c"\"mystring.h\"".as_ptr();
        header_files[2] = c"\"init.h\"".as_ptr();
        for ap in argv.iter().skip(1) {
            let fname = std::ffi::CString::new(ap.as_str()).unwrap();
            readfile(fname.as_ptr());
        }
        output();
        libc::rename(OUTTEMP.as_ptr(), OUTFILE.as_ptr());
        libc::exit(0);
        /* NOTREACHED */
    }
}

/*
 * Parse an input file.
 */

// [spec:dash:def:mkinit.readfile-fn]
// [spec:dash:sem:mkinit.readfile-fn]
unsafe fn readfile(fname: *const c_char) {
    let fp: *mut FILE;
    let mut line: [c_char; 1024] = [0; 1024];
    let mut ep: *mut event;

    fp = ckfopen(fname, c"r".as_ptr());
    curfile = fname;
    linno = 0;
    amiddecls = 0;
    while !libc::fgets(line.as_mut_ptr(), 1024, fp).is_null() {
        linno += 1;
        ep = ptr::addr_of_mut!(event) as *mut event;
        while ep < (ptr::addr_of_mut!(event) as *mut event).add(NEVENTS) {
            if line[0] == *(*ep).name.as_ptr() && r#match((*ep).name.as_ptr(), line.as_ptr()) != 0 {
                doevent(ep, fp, fname);
                break;
            }
            ep = ep.add(1);
        }
        if line[0] == b'I' as c_char && r#match(c"INCLUDE".as_ptr(), line.as_ptr()) != 0 {
            doinclude(line.as_mut_ptr());
        }
        if line[0] == b'M' as c_char && r#match(c"MKINIT".as_ptr(), line.as_ptr()) != 0 {
            dodecl(line.as_mut_ptr(), fp);
        }
        if line[0] == b'#' as c_char && gooddefine(line.as_ptr()) != 0 {
            let mut cp: *mut c_char;
            let mut line2: [c_char; 1024] = [0; 1024];
            static undef: &core::ffi::CStr = c"#undef ";

            libc::strcpy(line2.as_mut_ptr(), line.as_ptr());
            libc::memcpy(
                line2.as_mut_ptr() as *mut c_void,
                undef.as_ptr() as *const c_void,
                undef.to_bytes().len(),
            );
            cp = line2.as_mut_ptr().add(undef.to_bytes().len());
            while *cp != 0 && (*cp == b' ' as c_char || *cp == b'\t' as c_char) {
                cp = cp.add(1);
            }
            while *cp != 0
                && *cp != b' ' as c_char
                && *cp != b'\t' as c_char
                && *cp != b'\n' as c_char
            {
                cp = cp.add(1);
            }
            *cp = b'\n' as c_char;
            cp = cp.add(1);
            *cp = b'\0' as c_char;
            addstr(line2.as_ptr(), ptr::addr_of_mut!(defines));
            addstr(line.as_ptr(), ptr::addr_of_mut!(defines));
        }
    }
    libc::fclose(fp);
}

// [spec:dash:def:mkinit.match-fn]
// [spec:dash:sem:mkinit.match-fn]
unsafe fn r#match(name: *const c_char, line: *const c_char) -> c_int {
    let mut p: *const c_char;
    let mut q: *const c_char;

    p = name;
    q = line;
    while *p != 0 {
        let a = *p;
        p = p.add(1);
        let b = *q;
        q = q.add(1);
        if a != b {
            return 0;
        }
    }
    if *q != b'{' as c_char
        && *q != b' ' as c_char
        && *q != b'\t' as c_char
        && *q != b'\n' as c_char
    {
        return 0;
    }
    1
}

// [spec:dash:def:mkinit.gooddefine-fn]
// [spec:dash:sem:mkinit.gooddefine-fn]
unsafe fn gooddefine(line: *const c_char) -> c_int {
    let mut p: *const c_char;

    if r#match(c"#define".as_ptr(), line) == 0 {
        return 0; /* not a define */
    }
    p = line.add(7);
    while *p == b' ' as c_char || *p == b'\t' as c_char {
        p = p.add(1);
    }
    while *p != b' ' as c_char && *p != b'\t' as c_char {
        if *p == b'(' as c_char {
            return 0; /* macro definition */
        }
        p = p.add(1);
    }
    while *p != b'\n' as c_char && *p != b'\0' as c_char {
        p = p.add(1);
    }
    if *p.offset(-1) == b'\\' as c_char {
        return 0; /* multi-line definition */
    }
    1
}

// [spec:dash:def:mkinit.doevent-fn]
// [spec:dash:sem:mkinit.doevent-fn]
unsafe fn doevent(ep: *mut event, fp: *mut FILE, fname: *const c_char) {
    let mut line: [c_char; 1024] = [0; 1024];
    let mut indent: c_int;
    let mut p: *const c_char;

    libc::snprintf(
        line.as_mut_ptr(),
        line.len(),
        c"\n      /* from %s: */\n".as_ptr(),
        fname,
    );
    addstr(line.as_ptr(), ptr::addr_of_mut!((*ep).code));
    addstr(c"      {\n".as_ptr(), ptr::addr_of_mut!((*ep).code));
    loop {
        linno += 1;
        if libc::fgets(line.as_mut_ptr(), 1024, fp).is_null() {
            error("Unexpected EOF");
        }
        if equal(line.as_ptr(), c"}\n".as_ptr()) {
            break;
        }
        indent = 6;
        p = line.as_ptr();
        while *p == b'\t' as c_char {
            indent += 8;
            p = p.add(1);
        }
        while *p == b' ' as c_char {
            indent += 1;
            p = p.add(1);
        }
        if *p == b'\n' as c_char || *p == b'#' as c_char {
            indent = 0;
        }
        while indent >= 8 {
            addchar(b'\t' as c_int, ptr::addr_of_mut!((*ep).code));
            indent -= 8;
        }
        while indent > 0 {
            addchar(b' ' as c_int, ptr::addr_of_mut!((*ep).code));
            indent -= 1;
        }
        addstr(p, ptr::addr_of_mut!((*ep).code));
    }
    addstr(c"      }\n".as_ptr(), ptr::addr_of_mut!((*ep).code));
}

// [spec:dash:def:mkinit.doinclude-fn]
// [spec:dash:sem:mkinit.doinclude-fn]
unsafe fn doinclude(line: *mut c_char) {
    let mut p: *mut c_char;
    let name: *mut c_char;
    let mut pp: *mut *const c_char;

    p = line;
    while *p != b'"' as c_char && *p != b'<' as c_char && *p != b'\0' as c_char {
        p = p.add(1);
    }
    if *p == b'\0' as c_char {
        error("Expecting '\"' or '<'");
    }
    name = p;
    while *p != b' ' as c_char && *p != b'\t' as c_char && *p != b'\n' as c_char {
        p = p.add(1);
    }
    if *p.offset(-1) != b'"' as c_char && *p.offset(-1) != b'>' as c_char {
        error("Missing terminator");
    }
    *p = b'\0' as c_char;

    /* name now contains the name of the include file */
    pp = ptr::addr_of_mut!(header_files) as *mut *const c_char;
    while !(*pp).is_null() && !equal(*pp, name) {
        pp = pp.add(1);
    }
    if (*pp).is_null() {
        *pp = savestr(name);
    }
}

// [spec:dash:def:mkinit.dodecl-fn]
// [spec:dash:sem:mkinit.dodecl-fn]
unsafe fn dodecl(line1: *mut c_char, fp: *mut FILE) {
    let mut line: [c_char; 1024] = [0; 1024];
    let mut p: *mut c_char;
    let mut q: *mut c_char;

    if libc::strcmp(line1, c"MKINIT\n".as_ptr()) == 0 {
        /* start of struct/union decl */
        addchar(b'\n' as c_int, ptr::addr_of_mut!(decls));
        loop {
            linno += 1;
            if libc::fgets(line.as_mut_ptr(), 1024, fp).is_null() {
                error("Unterminated structure declaration");
            }
            addstr(line.as_ptr(), ptr::addr_of_mut!(decls));
            if line[0] == b'}' as c_char {
                break;
            }
        }
        amiddecls = 0;
    } else {
        if amiddecls == 0 {
            addchar(b'\n' as c_int, ptr::addr_of_mut!(decls));
        }
        q = ptr::null_mut();
        p = line1.add(6);
        while *p != 0 && libc::strchr(c"=/\n".as_ptr(), *p as c_int).is_null() {
            p = p.add(1);
        }
        if *p == b'=' as c_char {
            /* eliminate initialization */
            q = p;
            while *q != 0 && *q != b';' as c_char {
                q = q.add(1);
            }
            if *q == b'\0' as c_char {
                q = ptr::null_mut();
            } else {
                while *p.offset(-1) == b' ' as c_char {
                    p = p.offset(-1);
                }
                *p = b'\0' as c_char;
            }
        }
        addstr(c"extern".as_ptr(), ptr::addr_of_mut!(decls));
        addstr(line1.add(6), ptr::addr_of_mut!(decls));
        if !q.is_null() {
            addstr(q, ptr::addr_of_mut!(decls));
        }
        amiddecls = 1;
    }
}

/*
 * Write the output to the file OUTTEMP.
 */

// [spec:dash:def:mkinit.output-fn]
// [spec:dash:sem:mkinit.output-fn]
unsafe fn output() {
    let fp: *mut FILE;
    let mut pp: *mut *const c_char;
    let mut ep: *mut event;

    fp = ckfopen(OUTTEMP.as_ptr(), c"w".as_ptr());
    libc::fputs(writer.as_ptr(), fp);
    pp = ptr::addr_of_mut!(header_files) as *mut *const c_char;
    while !(*pp).is_null() {
        libc::fprintf(fp, c"#include %s\n".as_ptr(), *pp);
        pp = pp.add(1);
    }
    libc::fputs(c"\n\n\n".as_ptr(), fp);
    writetext(ptr::addr_of_mut!(defines), fp);
    libc::fputs(c"\n\n".as_ptr(), fp);
    writetext(ptr::addr_of_mut!(decls), fp);
    ep = ptr::addr_of_mut!(event) as *mut event;
    while ep < (ptr::addr_of_mut!(event) as *mut event).add(NEVENTS) {
        libc::fputs(c"\n\n\n".as_ptr(), fp);
        libc::fputs((*ep).comment.as_ptr(), fp);
        libc::fprintf(
            fp,
            c"\nvoid\n%s(%s) {\n".as_ptr(),
            (*ep).routine.as_ptr(),
            match (*ep).args {
                Some(a) => a.as_ptr(),
                None => c"".as_ptr(),
            },
        );
        writetext(ptr::addr_of_mut!((*ep).code), fp);
        libc::fprintf(fp, c"}\n".as_ptr());
        ep = ep.add(1);
    }
    libc::fclose(fp);
}

/*
 * A text structure is simply a block of text that is kept in memory.
 * Addstr appends a string to the text struct, and addchar appends a single
 * character.
 */

// [spec:dash:def:mkinit.addstr-fn]
// [spec:dash:sem:mkinit.addstr-fn]
unsafe fn addstr(mut s: *const c_char, text: *mut text) {
    while *s != 0 {
        (*text).nleft -= 1;
        if (*text).nleft < 0 {
            let c = *s;
            s = s.add(1);
            addchar(c as c_int, text);
        } else {
            *(*text).nextc = *s;
            (*text).nextc = (*text).nextc.add(1);
            s = s.add(1);
        }
    }
}

// [spec:dash:def:mkinit.addchar-fn]
// [spec:dash:sem:mkinit.addchar-fn]
unsafe fn addchar(c: c_int, text: *mut text) {
    let bp: *mut block;

    (*text).nleft -= 1;
    if (*text).nleft < 0 {
        bp = ckmalloc(core::mem::size_of::<block>() as c_int) as *mut block;
        if (*text).start.is_null() {
            (*text).start = bp;
        } else {
            (*(*text).last).next = bp;
        }
        (*text).last = bp;
        (*text).nextc = (*bp).text.as_mut_ptr();
        (*text).nleft = BLOCKSIZE as c_int - 1;
    }
    *(*text).nextc = c as c_char;
    (*text).nextc = (*text).nextc.add(1);
}

/*
 * Write the contents of a text structure to a file.
 */

// [spec:dash:def:mkinit.writetext-fn]
// [spec:dash:sem:mkinit.writetext-fn]
unsafe fn writetext(text: *mut text, fp: *mut FILE) {
    let mut bp: *mut block;

    if !(*text).start.is_null() {
        bp = (*text).start;
        while bp != (*text).last {
            if libc::fwrite(
                (*bp).text.as_ptr() as *const c_void,
                core::mem::size_of::<c_char>(),
                BLOCKSIZE,
                fp,
            ) != BLOCKSIZE
            {
                error("Can't write data\n");
            }
            bp = (*bp).next;
        }
        if libc::fwrite(
            (*bp).text.as_ptr() as *const c_void,
            core::mem::size_of::<c_char>(),
            BLOCKSIZE - (*text).nleft as usize,
            fp,
        ) != BLOCKSIZE - (*text).nleft as usize
        {
            error("Can't write data\n");
        }
    }
}

// [spec:dash:def:mkinit.ckfopen-fn]
// [spec:dash:sem:mkinit.ckfopen-fn]
unsafe fn ckfopen(file: *const c_char, mode: *const c_char) -> *mut FILE {
    let fp: *mut FILE;

    fp = libc::fopen(file, mode);
    if fp.is_null() {
        eprintln!(
            "Can't open {}",
            core::ffi::CStr::from_ptr(file).to_string_lossy()
        );
        libc::exit(2);
    }
    fp
}

// [spec:dash:def:mkinit.ckmalloc-fn]
// [spec:dash:sem:mkinit.ckmalloc-fn]
unsafe fn ckmalloc(nbytes: c_int) -> *mut c_void {
    let p: *mut c_char;

    p = libc::malloc(nbytes as libc::size_t) as *mut c_char;
    if p.is_null() {
        error("Out of space");
    }
    p as *mut c_void
}

// [spec:dash:def:mkinit.savestr-fn]
// [spec:dash:sem:mkinit.savestr-fn]
unsafe fn savestr(s: *const c_char) -> *mut c_char {
    let p: *mut c_char;

    p = ckmalloc(libc::strlen(s) as c_int + 1) as *mut c_char;
    libc::strcpy(p, s);
    p
}

// [spec:dash:def:mkinit.error-fn]
// [spec:dash:sem:mkinit.error-fn]
fn error(msg: &str) -> ! {
    unsafe {
        if !curfile.is_null() {
            eprint!(
                "{}:{}: ",
                core::ffi::CStr::from_ptr(curfile).to_string_lossy(),
                ptr::addr_of!(linno).read()
            );
        }
        eprintln!("{}", msg);
        libc::exit(2);
        /* NOTREACHED */
    }
}
