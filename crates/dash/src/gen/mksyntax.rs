//! Literal port of `src/mksyntax.c`.
//! Rules: `docs/spec/port/src/mksyntax.md`.
//!
//! This program creates syntax.h and syntax.c.
//!
//! It is a build-time code generator, not part of the shell; it is ported so
//! that `crate::syntax` stays derivable.  The C globals (`cfile`, `hfile`,
//! `syntax`) are passed as parameters instead, since nothing else in the
//! program observes them; everything else — control flow, loop bounds, the
//! column arithmetic in `print`, the order of the `add()` calls — is 1:1.

use core::ffi::CStr;

use libc::{c_char, c_int, c_void, FILE};

use crate::parser::{CTL_FIRST, CTL_LAST};

/// `fputs` for a Rust `str`; the C passes `char *` throughout and this is
/// only used where the C built the string with `sprintf` into `buf`.
unsafe fn fputs_str(s: &str, fp: *mut FILE) {
    libc::fwrite(s.as_ptr() as *const c_void, 1, s.len(), fp);
}

// [spec:dash:def:mksyntax.synclass]
struct synclass {
    name: &'static str,
    comment: &'static str,
}

/// Syntax classes.  The C array is NUL-terminated (`{ NULL, NULL }`) and the
/// loops stop on `synclass[i].name`; the Rust slice carries its own length,
/// so the sentinel is dropped.
static synclass: [synclass; 14] = [
    synclass { name: "CWORD", comment: "character is nothing special" },
    synclass { name: "CNL", comment: "newline character" },
    synclass { name: "CBACK", comment: "a backslash character" },
    synclass { name: "CSQUOTE", comment: "single quote" },
    synclass { name: "CDQUOTE", comment: "double quote" },
    synclass { name: "CENDQUOTE", comment: "a terminating quote" },
    synclass { name: "CBQUOTE", comment: "backwards single quote" },
    synclass { name: "CVAR", comment: "a dollar sign" },
    synclass { name: "CENDVAR", comment: "a '}' character" },
    synclass { name: "CLP", comment: "a left paren in arithmetic" },
    synclass { name: "CRP", comment: "a right paren in arithmetic" },
    synclass { name: "CEOF", comment: "end of file" },
    synclass { name: "CCTL", comment: "like CWORD, except it must be escaped" },
    synclass { name: "CSPCL", comment: "these terminate a word" },
];

/*
 * Syntax classes for is_ functions.  Warning:  if you add new classes
 * you may have to change the definition of the is_in_name macro.
 */
static is_entry: [synclass; 5] = [
    synclass { name: "ISDIGIT", comment: "a digit" },
    synclass { name: "ISUPPER", comment: "an upper case letter" },
    synclass { name: "ISLOWER", comment: "a lower case letter" },
    synclass { name: "ISUNDER", comment: "an underscore" },
    synclass { name: "ISSPECL", comment: "the name of a special parameter" },
];

static writer: &CStr = c"/*\n * This file was generated by the mksyntax program.\n */\n\n";

/// The C's `static char *syntax[513]`; only the first 257 entries are used.
type SyntaxTable = [&'static CStr; 513];

// [spec:dash:def:mksyntax.main-fn]
// [spec:dash:sem:mksyntax.main-fn]
pub fn main_fn(_argc: c_int, _argv: Vec<String>) -> c_int {
    unsafe {
        let cfile: *mut FILE;
        let hfile: *mut FILE;
        let mut syntax: SyntaxTable = [c""; 513];
        let mut i: usize;
        let buf: String;
        let mut pos: c_int;

        /* Create output files */
        cfile = libc::fopen(c"syntax.c".as_ptr(), c"w".as_ptr());
        if cfile.is_null() {
            libc::perror(c"syntax.c".as_ptr());
            libc::exit(2);
        }
        hfile = libc::fopen(c"syntax.h".as_ptr(), c"w".as_ptr());
        if hfile.is_null() {
            libc::perror(c"syntax.h".as_ptr());
            libc::exit(2);
        }
        libc::fputs(writer.as_ptr(), hfile);
        libc::fputs(writer.as_ptr(), cfile);

        libc::fputs(c"#include <ctype.h>\n".as_ptr(), hfile);
        libc::fputs(c"\n".as_ptr(), hfile);
        libc::fputs(c"#ifdef CEOF\n".as_ptr(), hfile);
        libc::fputs(c"#undef CEOF\n".as_ptr(), hfile);
        libc::fputs(c"#endif\n".as_ptr(), hfile);
        libc::fputs(c"\n".as_ptr(), hfile);

        /* Generate the #define statements in the header file */
        libc::fputs(c"/* Syntax classes */\n".as_ptr(), hfile);
        i = 0;
        while i < synclass.len() {
            let buf = format!("#define {} {}", synclass[i].name, i);
            fputs_str(&buf, hfile);
            pos = buf.len() as c_int;
            while pos < 32 {
                libc::fputc(b'\t' as c_int, hfile);
                pos = (pos + 8) & !0o7;
            }
            fputs_str(&format!("/* {} */\n", synclass[i].comment), hfile);
            i += 1;
        }
        libc::fputc(b'\n' as c_int, hfile);
        libc::fputs(c"/* Syntax classes for is_ functions */\n".as_ptr(), hfile);
        i = 0;
        while i < is_entry.len() {
            /* `%#o` of a non-zero value: a leading `0` then the octal digits */
            let buf = format!("#define {} 0{:o}", is_entry[i].name, 1 << i);
            fputs_str(&buf, hfile);
            pos = buf.len() as c_int;
            while pos < 32 {
                libc::fputc(b'\t' as c_int, hfile);
                pos = (pos + 8) & !0o7;
            }
            fputs_str(&format!("/* {} */\n", is_entry[i].comment), hfile);
            i += 1;
        }
        libc::fputc(b'\n' as c_int, hfile);
        buf = format!("#define SYNBASE {}\n", 129);
        fputs_str(&buf, hfile);
        fputs_str(&format!("#define PEOF {}\n\n", -129), hfile);
        libc::fputc(b'\n' as c_int, hfile);
        libc::fputs(c"#define BASESYNTAX (basesyntax + SYNBASE)\n".as_ptr(), hfile);
        libc::fputs(c"#define DQSYNTAX (dqsyntax + SYNBASE)\n".as_ptr(), hfile);
        libc::fputs(c"#define SQSYNTAX (sqsyntax + SYNBASE)\n".as_ptr(), hfile);
        libc::fputs(c"#define ARISYNTAX (arisyntax + SYNBASE)\n".as_ptr(), hfile);
        libc::fputc(b'\n' as c_int, hfile);
        output_type_macros(hfile); /* is_digit, etc. */
        libc::fputc(b'\n' as c_int, hfile);

        /* Generate the syntax tables. */
        libc::fputs(c"#include \"shell.h\"\n".as_ptr(), cfile);
        libc::fputs(c"#include \"syntax.h\"\n\n".as_ptr(), cfile);
        init(&mut syntax);
        libc::fputs(c"/* syntax table used when not in quotes */\n".as_ptr(), cfile);
        add(c"\n", c"CNL", &mut syntax);
        add(c"\\", c"CBACK", &mut syntax);
        add(c"'", c"CSQUOTE", &mut syntax);
        add(c"\"", c"CDQUOTE", &mut syntax);
        add(c"`", c"CBQUOTE", &mut syntax);
        add(c"$", c"CVAR", &mut syntax);
        add(c"}", c"CENDVAR", &mut syntax);
        add(c"<>();&| \t", c"CSPCL", &mut syntax);
        print(c"basesyntax", &syntax, cfile, hfile);
        init(&mut syntax);
        libc::fputs(c"\n/* syntax table used when in double quotes */\n".as_ptr(), cfile);
        add(c"\n", c"CNL", &mut syntax);
        add(c"\\", c"CBACK", &mut syntax);
        add(c"\"", c"CENDQUOTE", &mut syntax);
        add(c"`", c"CBQUOTE", &mut syntax);
        add(c"$", c"CVAR", &mut syntax);
        add(c"}", c"CENDVAR", &mut syntax);
        /* ':/' for tilde expansion, '-' for [a\-x] pattern ranges */
        add(c"^!*?[=~:/-]", c"CCTL", &mut syntax);
        print(c"dqsyntax", &syntax, cfile, hfile);
        init(&mut syntax);
        libc::fputs(c"\n/* syntax table used when in single quotes */\n".as_ptr(), cfile);
        add(c"\n", c"CNL", &mut syntax);
        add(c"'", c"CENDQUOTE", &mut syntax);
        /* ':/' for tilde expansion, '-' for [a\-x] pattern ranges */
        add(c"^!*?[=~:/-]\\", c"CCTL", &mut syntax);
        print(c"sqsyntax", &syntax, cfile, hfile);
        init(&mut syntax);
        libc::fputs(c"\n/* syntax table used when in arithmetic */\n".as_ptr(), cfile);
        add(c"\n", c"CNL", &mut syntax);
        add(c"\\", c"CBACK", &mut syntax);
        add(c"`", c"CBQUOTE", &mut syntax);
        add(c"$", c"CVAR", &mut syntax);
        add(c"}", c"CENDVAR", &mut syntax);
        add(c"(", c"CLP", &mut syntax);
        add(c")", c"CRP", &mut syntax);
        print(c"arisyntax", &syntax, cfile, hfile);
        filltable(c"0", &mut syntax);
        libc::fputs(c"\n/* character classification table */\n".as_ptr(), cfile);
        add(c"0123456789", c"ISDIGIT", &mut syntax);
        add(c"abcdefghijklmnopqrstucvwxyz", c"ISLOWER", &mut syntax);
        add(c"ABCDEFGHIJKLMNOPQRSTUCVWXYZ", c"ISUPPER", &mut syntax);
        add(c"_", c"ISUNDER", &mut syntax);
        add(c"#?$!-*@", c"ISSPECL", &mut syntax);
        print(c"is_type", &syntax, cfile, hfile);
        libc::exit(0);
        /* NOTREACHED */
    }
}

/*
 * Clear the syntax table.
 */

// [spec:dash:def:mksyntax.filltable-fn]
// [spec:dash:sem:mksyntax.filltable-fn]
fn filltable(dftval: &'static CStr, syntax: &mut SyntaxTable) {
    let mut i: usize;

    i = 0;
    while i < 257 {
        syntax[i] = dftval;
        i += 1;
    }
}

/*
 * Initialize the syntax table with default values.
 */

// [spec:dash:def:mksyntax.init-fn]
// [spec:dash:sem:mksyntax.init-fn]
fn init(syntax: &mut SyntaxTable) {
    let mut ctl: c_int;

    filltable(c"CWORD", syntax);
    syntax[0] = c"CEOF";
    ctl = CTL_FIRST;
    while ctl <= CTL_LAST {
        syntax[(129 + ctl) as usize] = c"CCTL";
        ctl += 1;
    }
}

/*
 * Add entries to the syntax table.
 */

// [spec:dash:def:mksyntax.add-fn]
// [spec:dash:sem:mksyntax.add-fn]
fn add(p: &CStr, ty: &'static CStr, syntax: &mut SyntaxTable) {
    for b in p.to_bytes() {
        syntax[(*b as c_char as c_int + 129) as usize] = ty;
    }
}

/*
 * Output the syntax table.
 */

// [spec:dash:def:mksyntax.print-fn]
// [spec:dash:sem:mksyntax.print-fn]
fn print(name: &CStr, syntax: &SyntaxTable, cfile: *mut FILE, hfile: *mut FILE) {
    unsafe {
        let mut i: c_int;
        let mut col: c_int;

        libc::fprintf(hfile, c"extern const char %s[];\n".as_ptr(), name.as_ptr());
        libc::fprintf(cfile, c"const char %s[] = {\n".as_ptr(), name.as_ptr());
        col = 0;
        i = 0;
        while i < 257 {
            if i == 0 {
                libc::fputs(c"      ".as_ptr(), cfile);
            } else if (i & 0o3) == 0 {
                libc::fputs(c",\n      ".as_ptr(), cfile);
                col = 0;
            } else {
                libc::fputc(b',' as c_int, cfile);
                loop {
                    col += 1;
                    if !(col < 9 * (i & 0o3)) {
                        break;
                    }
                    libc::fputc(b' ' as c_int, cfile);
                }
            }
            libc::fputs(syntax[i as usize].as_ptr(), cfile);
            col += syntax[i as usize].to_bytes().len() as c_int;
            i += 1;
        }
        libc::fputs(c"\n};\n".as_ptr(), cfile);
    }
}

/*
 * Output character classification macros (e.g. is_digit).  If digits are
 * contiguous, we can test for them quickly.
 */

static r#macro: [&CStr; 5] = [
    c"#define is_digit(c)\t((unsigned)((c) - '0') <= 9)\n",
    c"#define is_alpha(c)\tisalpha((unsigned char)(c))\n",
    c"#define is_name(c)\t((c) == '_' || isalpha((unsigned char)(c)))\n",
    c"#define is_in_name(c)\t((c) == '_' || isalnum((unsigned char)(c)))\n",
    c"#define is_special(c)\t((is_type+SYNBASE)[(signed char)(c)] & (ISSPECL|ISDIGIT))\n",
];

// [spec:dash:def:mksyntax.output-type-macros-fn]
// [spec:dash:sem:mksyntax.output-type-macros-fn]
fn output_type_macros(hfile: *mut FILE) {
    unsafe {
        for pp in r#macro.iter() {
            libc::fputs(pp.as_ptr(), hfile);
        }
        libc::fputs(c"#define digit_val(c)\t((c) - '0')\n".as_ptr(), hfile);
    }
}

// ---------------------------------------------------------------------
// Unit tests for this module's functions.
//
// Same shape as mksignames: the C generator ran during the reference
// build, so syntax.c and syntax.h in tests/.build/ref/src/ are an oracle
// for the whole program, and the helpers are asserted directly on a
// table.
// ---------------------------------------------------------------------
#[cfg(test)]
mod tests {
    use super::*;
    use crate::gen::mksignames::tests::reference;

    fn fresh() -> SyntaxTable {
        [c""; 513]
    }

    // [spec:dash:sem:mksyntax.filltable-fn/test]
    #[test]
    fn filltable_sets_the_first_257_entries_only() {
        let mut t = fresh();
        filltable(c"CWORD", &mut t);
        for i in 0..257 {
            assert_eq!(t[i], c"CWORD", "entry {i}");
        }
        // The table is 513 long but only 257 entries are used, and
        // filltable deliberately leaves the tail alone.
        for i in 257..513 {
            assert_eq!(t[i], c"", "entry {i} should be untouched");
        }
    }

    // [spec:dash:sem:mksyntax.init-fn/test]
    #[test]
    fn init_defaults_to_cword_with_ceof_and_the_control_range() {
        let mut t = fresh();
        init(&mut t);
        // Index 0 is EOF; the table is biased by 129 so that a signed
        // char index lands in range.
        assert_eq!(t[0], c"CEOF");
        for ctl in CTL_FIRST..=CTL_LAST {
            assert_eq!(t[(129 + ctl) as usize], c"CCTL", "ctl {ctl}");
        }
        // An ordinary character keeps the default.
        assert_eq!(t[(b'a' as c_int + 129) as usize], c"CWORD");
    }

    // [spec:dash:sem:mksyntax.add-fn/test]
    #[test]
    fn add_marks_every_character_of_the_string() {
        let mut t = fresh();
        filltable(c"CWORD", &mut t);
        add(c"()", c"CLP", &mut t);
        assert_eq!(t[(b'(' as c_int + 129) as usize], c"CLP");
        assert_eq!(t[(b')' as c_int + 129) as usize], c"CLP");
        assert_eq!(t[(b'a' as c_int + 129) as usize], c"CWORD");
        // The +129 bias is what lets a byte above 127 index the table
        // without going negative once it is taken as a signed char.
        add(c"\xff", c"CHIGH", &mut t);
        assert_eq!(t[(0xffu8 as c_char as c_int + 129) as usize], c"CHIGH");
    }

    // [spec:dash:sem:mksyntax.print-fn/test]
    // [spec:dash:sem:mksyntax.output-type-macros-fn/test]
    #[test]
    fn print_and_output_type_macros_emit_c_source() {
        let _g = crate::testutil::lock();
        unsafe {
            let dir = std::env::temp_dir().join(format!("mksyn-{}", libc::getpid()));
            std::fs::create_dir_all(&dir).unwrap();
            let (cp, hp) = (dir.join("c.txt"), dir.join("h.txt"));
            let cs = std::ffi::CString::new(cp.to_str().unwrap()).unwrap();
            let hs = std::ffi::CString::new(hp.to_str().unwrap()).unwrap();
            let cfile = libc::fopen(cs.as_ptr(), c"w".as_ptr());
            let hfile = libc::fopen(hs.as_ptr(), c"w".as_ptr());
            assert!(!cfile.is_null() && !hfile.is_null());

            let mut t = fresh();
            init(&mut t);
            print(c"basesyntax", &t, cfile, hfile);
            output_type_macros(hfile);
            libc::fclose(cfile);
            libc::fclose(hfile);

            let ctext = std::fs::read_to_string(&cp).unwrap();
            let htext = std::fs::read_to_string(&hp).unwrap();
            // The definition goes in the .c and the declaration in the
            // .h, and neither carries the 513 -- the array is written as
            // `const char basesyntax[] = {` and declared `extern const
            // char basesyntax[];`. The size lives only in the type alias
            // on the Rust side.
            assert!(ctext.contains("const char basesyntax[] = {"), "{ctext}");
            assert!(htext.contains("extern const char basesyntax[];"), "{htext}");
            assert!(ctext.contains("CEOF"));
            assert!(ctext.contains("CCTL"));
            // output_type_macros writes the is_* helpers into the header.
            assert!(htext.contains("is_digit"), "{htext}");
            std::fs::remove_dir_all(&dir).ok();
        }
    }

    // [spec:dash:sem:mksyntax.main-fn/test]
    #[test]
    fn main_fn_reproduces_the_c_generators_syntax_files() {
        let dir = std::env::temp_dir().join(format!("mksynmain-{}", unsafe { libc::getpid() }));
        std::fs::create_dir_all(&dir).unwrap();
        let path = dir.clone();
        // main_fn writes syntax.c and syntax.h into the CURRENT directory
        // and then exits, so it runs in a forked child that chdirs first.
        let rc = crate::testutil::forked(move || unsafe {
            let d = std::ffi::CString::new(path.to_str().unwrap()).unwrap();
            assert_eq!(libc::chdir(d.as_ptr()), 0);
            main_fn(1, vec!["mksyntax".to_string()]);
        });
        assert_eq!(rc, 0);

        for name in ["syntax.c", "syntax.h"] {
            let ours = std::fs::read_to_string(dir.join(name))
                .unwrap_or_else(|e| panic!("{name} not written: {e}"));
            assert!(ours.contains("generated by the mksyntax program"));
            match reference(name) {
                Some(theirs) => assert_eq!(
                    ours, theirs,
                    "{name}: the Rust generator and the C generator disagree"
                ),
                None => eprintln!(
                    "note: tests/.build/ref absent, skipped the {name} byte comparison"
                ),
            }
        }
        std::fs::remove_dir_all(&dir).ok();
    }
}
