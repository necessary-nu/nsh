// [spec:dash:def:parser.isassignment-fn]
// [spec:dash:sem:parser.isassignment-fn]
pub unsafe fn isassignment(p: *const c_char) -> c_int {
    let q = endofname(p);
    if p == q as *const c_char {
        return 0;
    }
    (*q == '=' as c_char) as c_int
}

