// [spec:dash:def:parser.parsecmd-fn]
// [spec:dash:sem:parser.parsecmd-fn]
pub unsafe fn parsecmd(interact: c_int) -> ParseResult {
    tokpushback = 0;
    checkkwd = 0;
    heredoclist = Vec::new();
    doprompt = interact;
    if doprompt != 0 {
        setprompt(doprompt);
    }
    needprompt = 0;
    list(1)
}

// [spec:dash:def:parser.list-fn]
// [spec:dash:sem:parser.list-fn]
unsafe fn list(nlflag: c_int) -> ParseResult {
    let mut nlflag = nlflag;
    let chknl = if nlflag & 1 != 0 { 0 } else { CHKNL };
    let mut n1: Option<Node>;
    let mut n2: Option<Node>;
    let mut tok: c_int;

    n1 = None;
    loop {
        checkkwd = chknl | CHKKWD | CHKALIAS;
        tok = readtoken();
        match tok {
            TNL => {
                parseheredoc();
                return ParseResult::Tree(n1);
            }

            TEOF => {
                let eof = n1.is_none() && chknl == 0;
                /* out_eof: */
                parseheredoc();
                tokpushback += 1;
                lasttoken = TEOF;
                return if eof {
                    ParseResult::Eof
                } else {
                    ParseResult::Tree(n1)
                };
            }
            _ => {}
        }

        tokpushback += 1;
        if nlflag == 2 && tokendlist[tok as usize] != 0 {
            return ParseResult::Tree(n1);
        }
        nlflag |= 2;

        /* The line the backgrounded command starts on, captured before
         * anything consumes it. `command()` and `pipeline()` both take
         * their `savelinno` at this same point, so a wrapper built here
         * records the line its contents record. */
        let savelinno: c_int = crate::plinno!();

        n2 = andor();
        tok = readtoken();
        if tok == TBACKGND {
            /* The C dereferences n2 unconditionally here. */
            if n2.as_ref().unwrap().node_type() == NPIPE {
                n2.as_mut().unwrap().npipe_mut().backgnd = 1;
            } else {
                if n2.as_ref().unwrap().node_type() != NREDIR {
                    /* dash never writes `linno` on this wrapper, so
                     * `evalsubshell` copies whatever `stalloc` returned
                     * into `lineno` and `errlinno` -- both observable, via
                     * `$LINENO` and the `sh: N:` diagnostic prefix. It is
                     * reached only on a fork failure, which is why nothing
                     * has noticed.
                     *
                     * There is no bug-for-bug option here: reading
                     * uninitialised memory is not something a safe
                     * language reproduces, so the only question is which
                     * correct value to write. See
                     * [dec:nsh:we-own-the-defects] and
                     * `docs/divergences.md`. */
                    n2 = Some(Node::Redir(nredir {
                        r#type: 0,
                        linno: savelinno,
                        n: n2.map(Box::new),
                        redirect: Vec::new(),
                    }));
                }
                n2.as_mut().unwrap().nredir_mut().r#type = NBACKGND;
            }
        }
        if n1.is_none() {
            n1 = n2;
        } else {
            n1 = Some(Node::Binary(nbinary {
                r#type: NSEMI,
                ch1: n1.map(Box::new),
                ch2: n2.map(Box::new),
            }));
        }
        match tok {
            TEOF => {
                /* goto out_eof */
                parseheredoc();
                tokpushback += 1;
                lasttoken = TEOF;
                return ParseResult::Tree(n1);
            }
            TNL => {
                tokpushback += 1;
                /* fall through */
            }
            TBACKGND | TSEMI => {}
            _ => {
                if chknl == 0 {
                    synexpect(-1);
                }
                tokpushback += 1;
                return ParseResult::Tree(n1);
            }
        }
    }
}

// [spec:dash:def:parser.andor-fn]
// [spec:dash:sem:parser.andor-fn]
unsafe fn andor() -> Option<Node> {
    let mut n1: Option<Node>;
    let mut t: c_int;

    n1 = pipeline();
    loop {
        t = readtoken();
        if t == TAND {
            t = NAND;
        } else if t == TOR {
            t = NOR;
        } else {
            tokpushback += 1;
            return n1;
        }
        checkkwd = CHKNL | CHKKWD | CHKALIAS;
        let n2 = pipeline();
        n1 = Some(Node::Binary(nbinary {
            r#type: t,
            ch1: n1.map(Box::new),
            ch2: n2.map(Box::new),
        }));
    }
}

// [spec:dash:def:parser.pipeline-fn]
// [spec:dash:sem:parser.pipeline-fn]
unsafe fn pipeline() -> Option<Node> {
    let mut n1: Option<Node>;
    let mut negate: c_int;

    negate = 0;
    /* TRACE(("pipeline: entered\n")); */
    if readtoken() == TNOT {
        negate = (negate == 0) as c_int;
        checkkwd = CHKKWD | CHKALIAS;
    } else {
        tokpushback += 1;
    }
    n1 = command();
    if readtoken() == TPIPE {
        /* Every `stalloc(sizeof(struct nodelist))` the C does here is one
         * `Vec` slot; the list is built front to back either way, and
         * `command()` cannot return NULL without having raised first. */
        let mut cmdlist: Vec<Node> = vec![n1.take().unwrap()];
        loop {
            checkkwd = CHKNL | CHKKWD | CHKALIAS;
            cmdlist.push(command().unwrap());
            if readtoken() != TPIPE {
                break;
            }
        }
        n1 = Some(Node::Pipe(npipe {
            backgnd: 0,
            cmdlist,
        }));
    }
    tokpushback += 1;
    if negate != 0 {
        Some(Node::Not(nnot {
            com: n1.map(Box::new),
        }))
    } else {
        n1
    }
}

// [spec:dash:def:parser.command-fn]
// [spec:dash:sem:parser.command-fn]
unsafe fn command() -> Option<Node> {
    let mut n1: Option<Node>;
    let mut t: c_int;
    let savelinno: c_int;

    savelinno = crate::plinno!();

    let mut goto_redir = false;
    let tok = readtoken();
    if tok == TIF {
        /* The C threads the elif chain through `elsepart` on the way down,
         * writing each new nif into its parent before parsing it.  An owned
         * tree cannot hand out that parent pointer, so the clauses are
         * collected in parse order and folded back up afterwards; the
         * sequence of `list(0)` calls — and so of everything they read — is
         * unchanged. */
        let mut clauses: Vec<(Option<Node>, Option<Node>)> = Vec::new();
        let test = list(0).into_node();
        if readtoken() != TTHEN {
            synexpect(TTHEN);
        }
        let ifpart = list(0).into_node();
        clauses.push((test, ifpart));
        while readtoken() == TELIF {
            let test = list(0).into_node();
            if readtoken() != TTHEN {
                synexpect(TTHEN);
            }
            let ifpart = list(0).into_node();
            clauses.push((test, ifpart));
        }
        let mut elsepart: Option<Node> = if lasttoken == TELSE {
            list(0).into_node()
        } else {
            tokpushback += 1;
            None
        };
        for (test, ifpart) in clauses.into_iter().rev() {
            elsepart = Some(Node::If(nif {
                test: test.map(Box::new),
                ifpart: ifpart.map(Box::new),
                elsepart: elsepart.map(Box::new),
            }));
        }
        n1 = elsepart;
        t = TFI;
    } else if tok == TWHILE || tok == TUNTIL {
        let got: c_int;
        let ty = if lasttoken == TWHILE { NWHILE } else { NUNTIL };
        let ch1 = list(0).into_node();
        got = readtoken();
        if got != TDO {
            synexpect(TDO);
        }
        let ch2 = list(0).into_node();
        n1 = Some(Node::Binary(nbinary {
            r#type: ty,
            ch1: ch1.map(Box::new),
            ch2: ch2.map(Box::new),
        }));
        t = TDONE;
    } else if tok == TFOR {
        if readtoken() != TWORD || quoteflag != 0 || goodname(wordtext_ptr()) == 0 {
            synerror(c"Bad for loop variable".as_ptr());
        }
        /* the C stores `wordtext` into the node here, before any further
         * token read can overwrite it */
        let var = wordtext_node();
        let mut args: Vec<Node> = Vec::new();
        checkkwd = CHKNL | CHKKWD | CHKALIAS;
        if readtoken() == TIN {
            while readtoken() == TWORD {
                args.push(Node::Arg(narg {
                    text: wordtext_node(),
                    backquote: takeglobal(addr_of_mut!(backquotelist)),
                }));
            }
            if lasttoken != TNL && lasttoken != TSEMI {
                synexpect(-1);
            }
        } else {
            /* The implicit `"$@"` of a `for` with no `in`. `dolatstr` is
             * seven bytes ending in the NUL that a word's text keeps, so
             * the value is the static and not what a C reader makes of
             * it. */
            let dolatstr: [u8; 7] = crate::mystring::dolatstr.map(|c| c as u8);
            args.push(Node::Arg(narg {
                text: NodeText::new(BString::from(&dolatstr[..])),
                backquote: Vec::new(),
            }));
            /*
             * Newline or semicolon here is optional (but note
             * that the original Bourne shell only allowed NL).
             */
            if lasttoken != TSEMI {
                tokpushback += 1;
            }
        }
        checkkwd = CHKNL | CHKKWD | CHKALIAS;
        if readtoken() != TDO {
            synexpect(TDO);
        }
        let body = list(0).into_node();
        n1 = Some(Node::For(nfor {
            linno: savelinno,
            args,
            body: body.map(Box::new),
            var,
        }));
        t = TDONE;
    } else if tok == TCASE {
        if readtoken() != TWORD {
            synexpect(TWORD);
        }
        let expr = Node::Arg(narg {
            text: wordtext_node(),
            backquote: takeglobal(addr_of_mut!(backquotelist)),
        });
        checkkwd = CHKNL | CHKKWD | CHKALIAS;
        if readtoken() != TIN {
            synexpect(TIN);
        }
        let mut cases: Vec<Node> = Vec::new();
        'next_case: loop {
            checkkwd = CHKNL | CHKKWD;
            t = readtoken();
            while t != TESAC {
                if lasttoken == TLP {
                    readtoken();
                }
                let mut pattern: Vec<Node> = Vec::new();
                loop {
                    if lasttoken < TWORD {
                        synexpect(TWORD);
                    }
                    pattern.push(Node::Arg(narg {
                        text: wordtext_node(),
                        backquote: takeglobal(addr_of_mut!(backquotelist)),
                    }));
                    if readtoken() != TPIPE {
                        break;
                    }
                    readtoken();
                }
                if lasttoken != TRP {
                    synexpect(TRP);
                }
                let body = list(2).into_node();
                cases.push(Node::Clist(nclist {
                    pattern,
                    body: body.map(Box::new),
                }));

                checkkwd = CHKNL | CHKKWD;
                t = readtoken();
                if t != TESAC {
                    if t != TENDCASE {
                        synexpect(TENDCASE);
                    } else {
                        continue 'next_case;
                    }
                }
            }
            break;
        }
        n1 = Some(Node::Case(ncase {
            linno: savelinno,
            expr: Some(Box::new(expr)),
            cases,
        }));
        goto_redir = true;
    } else if tok == TLP {
        let inner = list(0).into_node();
        n1 = Some(Node::Redir(nredir {
            r#type: NSUBSHELL,
            linno: savelinno,
            n: inner.map(Box::new),
            redirect: Vec::new(),
        }));
        t = TRP;
    } else if tok == TBEGIN {
        n1 = list(0).into_node();
        t = TEND;
    } else if tok == TWORD || tok == TREDIR {
        tokpushback += 1;
        return simplecmd();
    } else {
        synexpect(-1);
        /* NOTREACHED */
    }

    if !goto_redir {
        if readtoken() != t {
            synexpect(t);
        }
    }

    /* redir: */
    /* Now check for redirection which may follow command */
    checkkwd = CHKKWD | CHKALIAS;
    let mut redir: Vec<Node> = Vec::new();
    while readtoken() == TREDIR {
        /* The C copies `redirnode` into a local *before* `parsefname`,
         * because the token read inside it can set the global again.
         * Taking ownership of it here is the same guarantee. */
        let mut n2 = takeglobal(addr_of_mut!(redirnode)).unwrap();
        parsefname(&mut n2);
        redir.push(n2);
    }
    tokpushback += 1;
    if !redir.is_empty() {
        if n1.as_ref().map_or(true, |n| n.node_type() != NSUBSHELL) {
            n1 = Some(Node::Redir(nredir {
                r#type: NREDIR,
                linno: savelinno,
                n: n1.map(Box::new),
                redirect: Vec::new(),
            }));
        }
        n1.as_mut().unwrap().nredir_mut().redirect = redir;
    }

    n1
}

// [spec:dash:def:parser.simplecmd-fn]
// [spec:dash:sem:parser.simplecmd-fn]
unsafe fn simplecmd() -> Option<Node> {
    let mut args: Vec<Node> = Vec::new();
    let mut vars: Vec<Node> = Vec::new();
    let mut redir: Vec<Node> = Vec::new();
    let mut savecheckkwd: c_int;
    let savelinno: c_int;

    savecheckkwd = CHKALIAS;
    savelinno = crate::plinno!();
    loop {
        checkkwd = savecheckkwd;
        let tok = readtoken();
        if tok == TWORD {
            let n = Node::Arg(narg {
                text: wordtext_node(),
                backquote: takeglobal(addr_of_mut!(backquotelist)),
            });
            if savecheckkwd != 0 && isassignment(wordtext_ptr()) != 0 {
                vars.push(n);
            } else {
                args.push(n);
                savecheckkwd = 0;
            }
        } else if tok == TREDIR {
            let mut n = takeglobal(addr_of_mut!(redirnode)).unwrap();
            parsefname(&mut n); /* read name of redirection file */
            redir.push(n);
        } else {
            /* The C's `app == &args->narg.next` says the argument list holds
             * exactly one word, which is the name being defined. */
            if tok == TLP && args.len() == 1 && vars.is_empty() && redir.is_empty() {
                let bcmd: *const crate::builtins::builtincmd;
                let name: *const c_char;

                /* We have a function */
                if readtoken() != TRP {
                    synexpect(TRP);
                }
                /* the word becomes the function's name; the C keeps the same
                 * `char *` when it relabels the node */
                let word: narg = args.pop().unwrap().into_narg();
                name = word.text.as_ptr();
                bcmd = crate::exec::find_builtin(name);
                if goodname(name) == 0
                    || (!bcmd.is_null() && ((*bcmd).flags & crate::builtins::BUILTIN_SPECIAL) != 0)
                {
                    synerror(c"Bad function name".as_ptr());
                }
                /* The C relabels the NARG node NDEFUN in place: a union
                 * type-pun that copies `narg.text` (offset 16) into
                 * `ndefun.text` (offset 8) and overwrites the rest.  The
                 * NARG's backquote list is dropped either way. */
                checkkwd = CHKNL | CHKKWD | CHKALIAS;
                let linno = crate::plinno!();
                let body = command();
                return Some(Node::Defun(ndefun {
                    linno,
                    text: word.text,
                    body: body.map(Box::new),
                }));
            }
            /* fall through */
            /* default: */
            tokpushback += 1;
            break;
        }
    }
    /* out: */
    Some(Node::Cmd(ncmd {
        linno: savelinno,
        assign: vars,
        args,
        redirect: redir,
    }))
}

// [spec:dash:def:parser.makename-fn]
// [spec:dash:sem:parser.makename-fn]
unsafe fn makename() -> Node {
    Node::Arg(narg {
        text: wordtext_node(),
        backquote: takeglobal(addr_of_mut!(backquotelist)),
    })
}

// [spec:dash:def:parser.fixredir-fn]
// [spec:dash:sem:parser.fixredir-fn]
//
// Called twice with different owners: from `parsefname` while the node is
// still being built (`err == 0`), and from `expredir` on a tree that may be a
// shared function definition (`err != 0`).  Only the second writes at run
// time, and it only writes `dupfd`, which is why that field is the `Cell`.
pub unsafe fn fixredir(n: &Node, text: *const c_char, err: c_int) {
    /* TRACE(("Fix redir %s %d\n", text, err)); */
    let d = n.ndup();
    if err == 0 {
        *d.vname.borrow_mut() = None;
    }

    if is_digit(*text.offset(0) as c_int) && *text.offset(1) == 0 {
        d.dupfd.set(digit_val(*text.offset(0) as c_int));
    } else if *text.offset(0) == '-' as c_char && *text.offset(1) == 0 {
        d.dupfd.set(-1);
    } else {
        if err != 0 {
            let mut message = b"Bad fd number: ".to_vec();
            message.extend_from_slice(CStr::from_ptr(text).to_bytes());
            crate::error::sh_error(&message);
        } else {
            *d.vname.borrow_mut() = Some(Box::new(makename()));
        }
    }
}

// [spec:dash:def:parser.parsefname-fn]
// [spec:dash:sem:parser.parsefname-fn]
//
// The C reads the redirection node out of the `redirnode` global; here the
// caller has already taken ownership of it, because the `readtoken` below can
// set that global again before this function is done with it.
unsafe fn parsefname(n: &mut Node) {
    if n.node_type() == NHERE {
        checkkwd |= CHKEOFMARK;
    }
    if readtoken() != TWORD {
        synexpect(-1);
    }
    checkkwd &= !CHKEOFMARK;
    if n.node_type() == NHERE {
        /* the C reads the `heredoc` global here, after the token read */
        let mut here: heredoc = takeglobal(addr_of_mut!(heredoc)).unwrap();

        if quoteflag == 0 {
            n.nhere_mut().r#type = NXHERE;
        }
        /* TRACE(("Here document %d\n", n->type)); */
        /* `rmescapes` rewrites the word in place and can only shorten it, so
         * the new terminator is where the delimiter now ends. */
        let mut mark = takeglobal(addr_of_mut!(wordtext));
        rmescapes(mark.as_mut_ptr() as *mut c_char);
        let n_mark = libc::strlen(mark.as_ptr() as *const c_char);
        mark.truncate(n_mark);
        here.eofmark = mark;
        /* `parseheredoc` asked the node whether it was NXHERE; the type is
         * settled above, so the answer travels with the here-document. */
        here.expand = n.nhere().r#type == NXHERE;
        (&mut *addr_of_mut!(heredoclist)).push(here);
    } else if n.node_type() == NTOFD || n.node_type() == NFROMFD {
        fixredir(n, wordtext_ptr(), 0);
    } else {
        n.nfile_mut().fname = Some(Box::new(makename()));
    }
}

/*
 * Input any here documents.
 */

// [spec:dash:def:parser.parseheredoc-fn]
// [spec:dash:sem:parser.parseheredoc-fn]
unsafe fn parseheredoc() {
    let list: Vec<heredoc> = takeglobal(addr_of_mut!(heredoclist));

    for here in list {
        if needprompt != 0 {
            setprompt(2);
        }
        let mark = EofMark::Word(BStr::new(&here.eofmark));
        if !here.expand {
            readtoken1(pgetc(), SQSYNTAX(), mark, here.striptabs);
        } else {
            readtoken1(pgetc_eatbnl(), DQSYNTAX(), mark, here.striptabs);
        }
        let n = Node::Arg(narg {
            text: wordtext_node(),
            backquote: takeglobal(addr_of_mut!(backquotelist)),
        });
        /* `here->here->nhere.doc = n` in the C — the same slot, reached
         * through a shared handle instead of a back pointer.  It is written
         * exactly once, so a second write cannot happen. */
        let _ = here.doc.set(n);
    }
}

// [spec:dash:def:parser.readtoken-fn]
// [spec:dash:sem:parser.readtoken-fn]
unsafe fn readtoken() -> c_int {
    let mut t: c_int;
    let mut kwd: c_int = checkkwd;

    'top: loop {
        t = xxreadtoken();

        /*
         * eat newlines
         */
        if kwd & CHKNL != 0 {
            while t == TNL {
                parseheredoc();
                checkkwd = 0;
                t = xxreadtoken();
            }
        }

        kwd |= checkkwd;
        checkkwd = 0;

        if t != TWORD || quoteflag != 0 {
            break 'top;
        }

        /*
         * check for keywords
         */
        if kwd & CHKKWD != 0 {
            let pp: *const *const c_char = findkwd(wordtext_ptr());

            if !pp.is_null() {
                t = pp.offset_from(parsekwd.0.as_ptr()) as c_int + KWDOFFSET;
                lasttoken = t;
                break 'top;
            }
        }

        if kwd & CHKALIAS != 0 {
            let ap = crate::alias::lookupalias(wordtext_ptr(), 1);
            if !ap.is_null() {
                if *(*ap).val != 0 {
                    pushstring((*ap).val, ap as *mut c_void);
                }
                continue 'top;
            }
        }
        break 'top;
    }
    /* out: */
    t
}

// [spec:dash:def:parser.nlprompt-fn]
// [spec:dash:sem:parser.nlprompt-fn]
unsafe fn nlprompt() {
    crate::plinno!() += 1;
    if doprompt != 0 {
        setprompt(2);
    }
}

// [spec:dash:def:parser.nlnoprompt-fn]
// [spec:dash:sem:parser.nlnoprompt-fn]
unsafe fn nlnoprompt() {
    crate::plinno!() += 1;
    needprompt = doprompt;
}

/*
 * Read the next input token.
 * If the token is a word, we set backquotelist to the list of cmds in
 *	backquotes.  We set quoteflag to true if any part of the word was
 *	quoted.
 * If the token is TREDIR, then we set redirnode to a structure containing
 *	the redirection.
 */

// [spec:dash:def:parser.xxreadtoken-fn]
// [spec:dash:sem:parser.xxreadtoken-fn]
unsafe fn xxreadtoken() -> c_int {
    let mut c: c_int;

    if tokpushback != 0 {
        tokpushback = 0;
        return lasttoken;
    }
    if needprompt != 0 {
        setprompt(2);
    }
    loop {
        /* until token or start of word found */
        let tok: c_int;

        c = pgetc_eatbnl();
        if c == ' ' as c_int || c == '\t' as c_int {
            continue;
        } else if c == '#' as c_int {
            loop {
                c = pgetc();
                if c == '\n' as c_int || c == PEOF {
                    break;
                }
            }
            pungetc();
            continue;
        } else if c == '\n' as c_int {
            nlnoprompt();
            lasttoken = TNL;
            return TNL;
        } else if c == PEOF {
            lasttoken = TEOF;
            return TEOF;
        } else if c == '&' as c_int {
            if pgetc_eatbnl() == '&' as c_int {
                lasttoken = TAND;
                return TAND;
            }
            pungetc();
            lasttoken = TBACKGND;
            return TBACKGND;
        } else if c == '|' as c_int {
            if pgetc_eatbnl() == '|' as c_int {
                lasttoken = TOR;
                return TOR;
            }
            pungetc();
            lasttoken = TPIPE;
            return TPIPE;
        } else if c == ';' as c_int {
            if pgetc_eatbnl() == ';' as c_int {
                lasttoken = TENDCASE;
                return TENDCASE;
            }
            pungetc();
            lasttoken = TSEMI;
            return TSEMI;
        } else if c == '(' as c_int {
            lasttoken = TLP;
            return TLP;
        } else if c == ')' as c_int {
            lasttoken = TRP;
            return TRP;
        }
        tok = readtoken1(c, BASESYNTAX(), EofMark::None, 0);
        if tok != TBLANK {
            return tok;
        }
    }
}

// [spec:dash:def:parser.pgetc-eatbnl-fn]
// [spec:dash:sem:parser.pgetc-eatbnl-fn]
unsafe fn pgetc_eatbnl() -> c_int {
    let mut c: c_int;

    loop {
        c = pgetc();
        if c != '\\' as c_int {
            break;
        }
        if pgetc() != '\n' as c_int {
            pungetc();
            break;
        }

        nlprompt();
    }

    c
}

// [spec:dash:def:parser.pgetc-top-fn]
// [spec:dash:sem:parser.pgetc-top-fn]
unsafe fn pgetc_top(stack: &synstack) -> c_int {
    if stack.syntax == SQSYNTAX() {
        pgetc()
    } else {
        pgetc_eatbnl()
    }
}

