// [spec:dash:def:parser.getmbc-fn]
// [spec:dash:sem:parser.getmbc-fn]
pub unsafe fn getmbc(c: c_int, out: *mut c_char, mode: c_int) -> c_uint {
    let mut c = c;
    let mut out = out;
    let start: *mut c_char = out;
    let mut mbst: libc::mbstate_t = mem::zeroed();
    let mut ml: c_uint = 0;
    let mut ml2: usize;
    let mut wc: libc::wchar_t = 0;
    let mbc: *mut c_char;

    if c >= 0 || c <= PEOF {
        return 0;
    }

    mbc = if (mode & 3) < 2 {
        out.offset(2 + (mode == 1) as isize)
    } else {
        out
    };
    *mbc.offset(ml as isize) = c as c_char;
    loop {
        ml2 = mbrtowc(&mut wc, mbc.offset(ml as isize), 1, &mut mbst);
        ml += 1;
        if ml2 != (-2isize) as usize {
            break;
        }
        if ml as usize >= MB_LEN_MAX {
            break;
        }
        c = pgetc_eoa();
        if c == PEOA || c == PEOF {
            break;
        }
        *mbc.offset(ml as isize) = c as c_char;
    }

    if ml2 == 1 && ml > 1 {
        if mode == 4 && iswblank(wc as u32) != 0 {
            return 1;
        }

        if (mode & 3) < 2 {
            USTPUTC!(CTLMBCHAR, out);
            if mode == 1 {
                USTPUTC!(CTLESC, out);
            }
            USTPUTC!(ml, out);
        }
        STADJUST!(ml, out);
        if (mode & 3) < 2 {
            USTPUTC!(ml, out);
            USTPUTC!(CTLMBCHAR, out);
        }

        return (out as usize - start as usize) as c_uint;
    }

    if ml > 1 {
        pungetn(ml as c_int - 1);
    }

    0
}

/// The most `getmbc` or `conv_escape` can write past the cursor.
///
/// `readtoken1` spells it `CHECKSTRSPACE(MAX(MB_LEN_MAX, 16) + 7, out)` and
/// then lets both of them write through a bare `char *`. Reserving is what
/// makes those writes land in a `Vec`'s spare capacity rather than past the
/// end of it, so the number has to stay the C's.
const MBSLOP: usize = (if MB_LEN_MAX > 16 { MB_LEN_MAX } else { 16 }) + 7;

/// `getmbc` appending to a growable string.
///
/// The C hands it a cursor into the stack block; the byte count it returns is
/// how far that cursor moved, which here is what the caller commits. It can
/// also return 0 or 1 having scribbled on the block past the cursor, and the
/// C leaves that scribble for the next write to overwrite — so does this,
/// because the bytes stay uncommitted.
unsafe fn getmbc_at(out: &mut BString, c: c_int, mode: c_int) -> c_uint {
    out.reserve(MBSLOP);
    let len = out.len();
    getmbc(c, out.as_mut_ptr().add(len) as *mut c_char, mode)
}

// [spec:dash:def:parser.dollarsq-escape-fn]
// [spec:dash:sem:parser.dollarsq-escape-fn]
unsafe fn dollarsq_escape(dest: &mut BString) {
    dest.reserve(MBSLOP);
    let base = dest.len();
    let mut out: *mut c_char = dest.as_mut_ptr().add(base) as *mut c_char;
    /* 10 = length of UXXXXXXXX + NUL */
    let mut str: [c_char; 10] = [0; 10];
    let mut len: c_uint;
    let mut p: *mut c_char;

    len = 0;
    while (len as usize) < mem::size_of_val(&str) - 1 {
        let c = pgetc();

        if c <= PEOF {
            break;
        }

        str[len as usize] = c as c_char;
        len += 1;

        if c == '\'' as c_int {
            break;
        }
    }
    str[len as usize] = 0;

    p = str.as_mut_ptr();
    if *p != 'c' as c_char {
        let ret: c_uint;

        ret = crate::escape::conv_escape(p, out, true);
        p = p.offset((ret >> 4) as isize);
        out = out.offset((ret & 15) as isize);
    } else {
        p = p.offset(1);
        if *p != 0 {
            let conv_ch: c_int;
            let c: c_int;

            c = *p as u8 as c_int;
            p = p.offset(1);

            p = p.offset((((c ^ *p as c_int) | (c ^ '\\' as c_int)) == 0) as isize);

            conv_ch = (c & !((c & 0x40) >> 1) & 0x7f) ^ 0x40;
            USTPUTC!(conv_ch, out);
        }
    }

    pungetn((len as isize - (p as isize - str.as_ptr() as isize)) as c_int);
    let written = out as usize - (dest.as_ptr().add(base) as usize);
    dest.set_len(base + written);
}

/*
 * If eofmark is NULL, read a word or a redirection symbol.  If eofmark
 * is not NULL, read a here document.  In the latter case, eofmark is the
 * word which marks the end of the document and striptabs is true if
 * leading tabs should be stripped from the document.  The argument firstc
 * is the first character of the input token or document.
 *
 * Because C does not have internal subroutines, the original simulates
 * them with goto's: CHECKEND, PARSEREDIR, PARSESUB, PARSEBACKQOLD,
 * PARSEBACKQNEW and PARSEARITH run code that appears at the end of
 * readtoken1.  Here they are plain functions taking the shared C locals
 * (`Rt1`) by `&mut`; they are called from exactly the same places and
 * mutate the state in exactly the same order.
 */

/// The locals of `readtoken1` that its internal subroutines share.
struct Rt1<'a> {
    /// Owned parse contexts, base first and current last. Popping retains the
    /// allocation, matching the C's reuse of its most recently popped level.
    synstack: Vec<synstack>,
    chkeofmark: c_int,
    printesc: bool,
    bqlist: Vec<Option<Node>>,
    dollarsq: c_int,
    c: c_int,
    quotef: c_int,
    /// The word being built. The C's `out` is a `char *` cursor into the
    /// stack block and `stackblock()` is the base; here the base is the
    /// buffer, the cursor is its length, and `STADJUST` is `truncate` or a
    /// `set_len` over bytes a raw writer has already filled.
    out: BString,
    eofmark: EofMark<'a>,
    striptabs: c_int,
    /// Backing store for the `alloca`'d pushback strings in `checkend`,
    /// which likewise accumulate for the life of the call.
    strpool: Vec<Vec<u8>>,
}

impl Rt1<'_> {
    #[inline]
    fn syn(&self) -> &synstack {
        self.synstack.last().unwrap()
    }

    #[inline]
    fn syn_mut(&mut self) -> &mut synstack {
        self.synstack.last_mut().unwrap()
    }
}

/// The label targets inside readtoken1's character switch that are
/// reached by `goto` from more than one case.
enum Lbl {
    None,
    Csquote,
    Quotemark,
    Toggledq,
    EndBackq,
}

// [spec:dash:def:parser.readtoken1-fn]
// [spec:dash:sem:parser.readtoken1-fn]
unsafe fn readtoken1(
    firstc: c_int,
    syntax: *const Syntax,
    eofmark: EofMark<'_>,
    striptabs: c_int,
) -> c_int {
    let mut st = Rt1 {
        synstack: vec![synstack {
            syntax,
            innerdq: 0,
            varpushed: 0,
            dblquote: (syntax == DQSYNTAX()) as c_int,
            backq: 0,
            varnest: 0,
            parenlevel: 0,
            dqvarnest: 0,
        }],
        chkeofmark: checkkwd & CHKEOFMARK,
        printesc: syntax == SQSYNTAX(),
        bqlist: Vec::new(),
        dollarsq: 0,
        c: firstc,
        quotef: 0,
        out: BString::new(Vec::new()),
        eofmark,
        striptabs,
        strpool: Vec::new(),
    };
    let len: usize;

    'loop_: loop {
        /* for each line, until end of word */
        checkend(&mut st); /* set c to PEOF if at end of here document */
        /* Until end of line or end of word */
        loop {
            'body: {
                let fieldsplitting: c_int;
                let mut ml: c_uint;

                fieldsplitting = if st.syn().syntax == BASESYNTAX()
                    && (st.syn().varnest | st.syn().backq) == 0
                {
                    4
                } else {
                    0
                };
                /* The C's CHECKSTRSPACE, which permits max(MB_LEN_MAX, 23)
                 * calls to USTPUTC, is `getmbc_at`'s reserve. */
                ml = getmbc_at(
                    &mut st.out,
                    st.c,
                    fieldsplitting | (if st.printesc { 2 } else { 0 }),
                );
                if ml == 1 {
                    if st.out.is_empty() {
                        return TBLANK;
                    }
                    st.c = pgetc();
                    break 'loop_;
                }
                let grown = st.out.len() + ml as usize;
                st.out.set_len(grown);
                if ml != 0 {
                    break 'body; /* continue */
                }

                let cls = syn_at(st.syn().syntax, st.c);
                let mut lbl = Lbl::None;

                if cls == CNL as c_int {
                    /* '\n' */
                    if fieldsplitting != 0 {
                        break 'loop_; /* exit outer loop */
                    }
                    st.out.push(st.c as u8);
                    nlprompt();
                    st.c = pgetc_top(st.syn());
                    continue 'loop_; /* continue outer loop */
                } else if cls == CWORD as c_int {
                    st.out.push(st.c as u8);
                } else if cls == CCTL as c_int {
                    if st.c == st.dollarsq {
                        dollarsq_escape(&mut st.out);
                    } else {
                        if (st.eofmark.is_none() as c_int | st.syn().dblquote | st.syn().varnest)
                            != 0
                        {
                            st.out.push(CTLESC as u8);
                        }
                        st.out.push(st.c as u8);
                    }
                } else if cls == CBACK as c_int {
                    /* backslash */
                    st.c = pgetc();
                    if st.c == PEOF {
                        st.out.push(CTLESC as u8);
                        st.out.push('\\' as u8);
                        pungetc();
                    } else {
                        if (st.syn().dblquote | st.syn().backq) != 0
                            && st.c != '\\' as c_int
                            && st.c != '`' as c_int
                            && st.c != '$' as c_int
                            && (st.c != '"' as c_int
                                || (!st.eofmark.is_none() && st.syn().varnest == 0))
                            && (st.c != '}' as c_int || st.syn().varnest == 0)
                        {
                            st.out.push(CTLESC as u8);
                            st.out.push('\\' as u8);
                        }
                        st.quotef += 1;

                        ml = getmbc_at(&mut st.out, st.c, 1);
                        let grown = st.out.len() + ml as usize;
                        st.out.set_len(grown);
                        if ml == 0 {
                            st.out.push(CTLESC as u8);
                            st.out.push(st.c as u8);
                        }
                    }
                } else if cls == CSQUOTE as c_int {
                    lbl = Lbl::Csquote;
                } else if cls == CDQUOTE as c_int {
                    st.syn_mut().syntax = DQSYNTAX();
                    st.syn_mut().dblquote = 1;
                    lbl = Lbl::Toggledq;
                } else if cls == CENDQUOTE as c_int {
                    if !st.eofmark.is_none() && st.syn().varnest == 0 {
                        st.out.push(st.c as u8);
                    } else {
                        if st.syn().dqvarnest == 0 {
                            if st.dollarsq != 0 {
                                /* `*out = '\0'; out = p + strlen(p);` — a NUL
                                 * written by a `$'\0'` escape ends the word,
                                 * so the cursor winds back to it. */
                                let end =
                                    st.out.iter().position(|&b| b == 0).unwrap_or(st.out.len());
                                st.out.truncate(end);
                                st.dollarsq = 0;
                            }

                            st.syn_mut().syntax = BASESYNTAX();
                            st.syn_mut().dblquote = 0;
                        }

                        st.quotef += 1;

                        if st.c == '"' as c_int {
                            lbl = Lbl::Toggledq;
                        } else {
                            lbl = Lbl::Quotemark;
                        }
                    }
                } else if cls == CVAR as c_int {
                    /* '$' */
                    if parsesub(&mut st) {
                        /* parse substitution */
                        lbl = Lbl::Csquote;
                    }
                } else if cls == CENDVAR as c_int {
                    /* '}' */
                    if st.syn().innerdq == 0 && st.syn().varnest > 0 {
                        st.syn_mut().varnest -= 1;
                        if st.syn().varnest == 0 && st.syn().varpushed != 0 {
                            synstack_ops::pop(&mut st.synstack);
                        } else if st.syn().dqvarnest > 0 {
                            st.syn_mut().dqvarnest -= 1;
                        }
                        if st.chkeofmark == 0 {
                            st.c = CTLENDVAR;
                        }
                    }
                    st.out.push(st.c as u8);
                } else if cls == CLP as c_int {
                    /* '(' in arithmetic */
                    st.syn_mut().parenlevel += 1;
                    st.out.push(st.c as u8);
                } else if cls == CRP as c_int {
                    /* ')' in arithmetic */
                    if st.syn().parenlevel > 0 {
                        st.syn_mut().parenlevel -= 1;
                    } else if pgetc_eatbnl() == ')' as c_int {
                        synstack_ops::pop(&mut st.synstack);
                        if st.chkeofmark != 0 {
                            st.out.push(st.c as u8);
                        } else {
                            st.c = CTLENDARI;
                        }
                    } else {
                        /*
                         * unbalanced parens
                         *  (don't 2nd guess - no error)
                         */
                        pungetc();
                    }
                    st.out.push(st.c as u8);
                } else if cls == CBQUOTE as c_int {
                    /* '`' */
                    if st.syn().backq == 2 {
                        lbl = Lbl::EndBackq;
                    } else {
                        st.out.push('`' as u8);
                        parsebackq(&mut st, 1);
                    }
                } else if cls == CEOF as c_int {
                    break 'loop_; /* exit outer loop */
                } else {
                    /* default: */
                    if st.c == ')' as c_int && st.syn().backq == 1 {
                        lbl = Lbl::EndBackq;
                    } else if fieldsplitting != 0 {
                        break 'loop_; /* exit outer loop */
                    } else {
                        st.out.push(st.c as u8);
                    }
                }

                /* the goto-linked tails of the switch above */
                loop {
                    match lbl {
                        Lbl::None => break,
                        Lbl::Csquote => {
                            /* csquote: */
                            st.syn_mut().syntax = SQSYNTAX();
                            lbl = Lbl::Quotemark;
                        }
                        Lbl::Quotemark => {
                            /* quotemark: */
                            if st.eofmark.is_none() {
                                st.out.push(CTLQUOTEMARK as u8);
                            }
                            lbl = Lbl::None;
                        }
                        Lbl::Toggledq => {
                            /* toggledq: */
                            if st.syn().varnest != 0 {
                                st.syn_mut().innerdq ^= 1;
                            }
                            lbl = Lbl::Quotemark;
                        }
                        Lbl::EndBackq => {
                            /* end_backq: */
                            synstack_ops::pop(&mut st.synstack);
                            st.printesc = false;
                            st.out.push(st.c as u8);
                            lbl = Lbl::None;
                        }
                    }
                }
            }
            st.c = pgetc_top(st.syn());
        }
    }
    /* endword: */
    if st.syn().syntax == ARISYNTAX() {
        synerror(c"Missing '))'".as_ptr());
    }
    if (st.syn().syntax != BASESYNTAX() && st.eofmark.is_none()) || st.syn().backq != 0 {
        synerror(c"Unterminated quoted string".as_ptr());
    }
    if st.syn().varnest != 0 {
        /* { */
        synerror(c"Missing '}'".as_ptr());
    }
    st.out.push(b'\0');
    len = st.out.len();
    if st.eofmark.is_none() {
        if (st.c == '>' as c_int || st.c == '<' as c_int)
            && st.quotef == 0
            && len <= 2
            && (st.out[0] == 0 || is_digit(st.out[0] as i8 as c_int))
        {
            parseredir(&mut st);
            lasttoken = TREDIR;
            return TREDIR;
        } else {
            pungetc();
        }
    }
    quoteflag = st.quotef;
    backquotelist = mem::take(&mut st.bqlist);
    /* `grabstackblock(len)` reserved the bytes the C had been writing into
     * scratch space, which is what made `wordtext` outlive the next token.
     * Moving the buffer out is the same guarantee. */
    wordtext = mem::take(&mut st.out);
    lasttoken = TWORD;
    TWORD
}
/* end of readtoken routine */

/*
 * Check to see whether we are at the end of the here document.  When this
 * is called, c is set to the first character of the next input line.  If
 * we are at the end of the here document, this routine sets the c to PEOF.
 */

/* checkend: */
unsafe fn checkend(st: &mut Rt1<'_>) {
    if let Some(mark) = st.eofmark.real() {
        let markloc: usize;
        let mut i: usize;
        let mut more_heredoc = false;

        if st.striptabs != 0 {
            while st.c == '\t' as c_int {
                st.c = pgetc();
            }
        }

        /* The C reads the candidate delimiter into the word being built and
         * then winds the cursor back to `markloc`, so the scratch is the tail
         * of the same buffer. */
        markloc = st.out.len();
        i = 0;
        loop {
            st.out.push(st.c as u8);
            if i == mark.len() {
                /* `*p == '\0'` — the delimiter's terminator */
                break;
            }
            if st.c != mark[i] as i8 as c_int {
                more_heredoc = true; /* goto more_heredoc */
                break;
            }

            st.c = pgetc();
            i += 1;
        }

        if !more_heredoc {
            if st.c == '\n' as c_int || st.c == PEOF {
                st.c = PEOF;
                nlnoprompt();
            } else {
                more_heredoc = true;
            }
        }

        if more_heredoc {
            let mut len: usize;

            /* more_heredoc: */
            let start = markloc + 1;
            len = st.out.len() - start;

            if len != 0 {
                len -= (st.c <= PEOF) as usize;
                st.c = st.out[start - 1] as i8 as c_int;

                if len != 0 {
                    let str: *mut c_char;

                    /* str = alloca(len + 1) */
                    let mut copy: Vec<u8> = Vec::with_capacity(len + 1);
                    copy.extend_from_slice(&st.out[start..start + len]);
                    copy.push(0);
                    st.strpool.push(copy);
                    let last = st.strpool.len() - 1;
                    str = st.strpool[last].as_mut_ptr() as *mut c_char;

                    pushstring(str, ptr::null_mut());
                }
            }
        }

        st.out.truncate(markloc);
    }
    /* goto checkend_return; */
}

/*
 * Parse a redirection operator.  The variable "out" points to a string
 * specifying the fd to be redirected.  The variable "c" contains the
 * first character of the redirection operator.
 */

/* parseredir: */
unsafe fn parseredir(st: &mut Rt1<'_>) {
    let fdc: c_char = st.out[0] as c_char;
    /* The C carves one `struct nfile` and then decides what it is by
     * assigning `np->type`, re-allocating only because `nhere` is smaller.
     * The arm has to be chosen up front here, so the type and the fd are
     * worked out first and the node built at the end. */
    let mut fd: c_int;
    let ty: c_int;
    let mut doc: Option<heredoc_body> = None;

    if st.c == '>' as c_int {
        fd = 1;
        st.c = pgetc_eatbnl();
        if st.c == '>' as c_int {
            ty = NAPPEND;
        } else if st.c == '|' as c_int {
            ty = NCLOBBER;
        } else if st.c == '&' as c_int {
            ty = NTOFD;
        } else {
            ty = NTO;
            pungetc();
        }
    } else {
        /* c == '<' */
        fd = 0;
        st.c = pgetc_eatbnl();
        if st.c == '<' as c_int {
            ty = NHERE;
            let slot: heredoc_body = Rc::new(OnceCell::new());
            let mut here = heredoc {
                doc: Rc::clone(&slot),
                expand: false,
                eofmark: BString::new(Vec::new()),
                striptabs: 0,
            };
            doc = Some(slot);
            st.c = pgetc_eatbnl();
            if st.c == '-' as c_int {
                here.striptabs = 1;
            } else {
                here.striptabs = 0;
                pungetc();
            }
            heredoc = Some(here);
        } else if st.c == '&' as c_int {
            ty = NFROMFD;
        } else if st.c == '>' as c_int {
            ty = NFROMTO;
        } else {
            ty = NFROM;
            pungetc();
        }
    }
    if fdc != '\0' as c_char {
        fd = digit_val(fdc as c_int);
    }
    redirnode = Some(match ty {
        NTOFD | NFROMFD => Node::Dup(ndup {
            r#type: ty,
            fd,
            dupfd: Cell::new(0),
            vname: RefCell::new(None),
        }),
        NHERE => Node::Here(nhere {
            r#type: NHERE,
            fd,
            doc: doc.unwrap(),
        }),
        _ => Node::File(nfile {
            r#type: ty,
            fd,
            fname: None,
            expfname: RefCell::new(None),
        }),
    });
    /* goto parseredir_return; */
}

/*
 * Parse a substitution.  At this point, we have read the dollar sign
 * and nothing else.
 *
 * Returns true where the C does `goto csquote`, i.e. jumps back into the
 * CSQUOTE arm of readtoken1's switch instead of returning normally.
 */

/* parsesub: */
unsafe fn parsesub(st: &mut Rt1<'_>) -> bool {
    let mut newsyn: *const Syntax = st.syn().syntax;
    static types: [u8; 6] = *b"}-+?=\0";
    let mut subtype: c_int;

    st.out.push('$' as u8);

    st.c = pgetc_eatbnl();
    if st.c == '(' as c_int {
        /* $(command) or $((arith)) */
        st.out.push(st.c as u8);
        if pgetc_eatbnl() == '(' as c_int {
            parsearith(st);
        } else {
            pungetc();
            parsebackq(st, 0);
        }
    } else if st.c == '\'' as c_int && syn_at(newsyn, '&' as c_int) != 0 {
        st.out.pop();
        st.dollarsq = '\\' as c_int;
        return true; /* goto csquote */
    } else if st.c == '{' as c_int || is_name(st.c) || is_special(st.c) != 0 {
        let typeloc: usize = st.out.len();
        let mut badsub = false;

        /* `STADJUST(chkeofmark == 0, out)` steps over the byte the CTLVAR
         * subtype lands in below; nothing reads it in between, so the
         * placeholder value is not observable. */
        st.out.resize(typeloc + (st.chkeofmark == 0) as usize, 0);
        subtype = VSNORMAL;
        if st.c == '{' as c_int {
            if st.chkeofmark != 0 {
                st.out.push('{' as u8);
            }
            st.c = pgetc_eatbnl();
            subtype = 0;
        }
        'varname: loop {
            if is_name(st.c) {
                loop {
                    st.out.push(st.c as u8);
                    st.c = pgetc_eatbnl();
                    if !is_in_name(st.c) {
                        break;
                    }
                }
            } else if is_digit(st.c) {
                loop {
                    st.out.push(st.c as u8);
                    st.c = pgetc_eatbnl();
                    if !((subtype <= 0 || subtype >= VSLENGTH) && is_digit(st.c)) {
                        break;
                    }
                }
            } else if st.c != '}' as c_int {
                let mut cc = st.c;

                st.c = pgetc_eatbnl();

                if subtype == 0 && cc == '#' as c_int {
                    subtype = VSLENGTH;

                    if st.c == '_' as c_int || libc::isalnum(st.c) != 0 {
                        if st.chkeofmark != 0 {
                            st.out.push('#' as u8);
                        }
                        continue 'varname; /* goto varname */
                    }

                    cc = st.c;
                    st.c = pgetc_eatbnl();
                    if cc == '}' as c_int || st.c != '}' as c_int {
                        pungetc();
                        subtype = 0;
                        st.c = cc;
                        cc = '#' as c_int;
                    } else if st.chkeofmark != 0 {
                        st.out.push('#' as u8);
                    }
                }

                if is_special(cc) == 0 {
                    if subtype == VSLENGTH {
                        subtype = 0;
                    }
                    badsub = true; /* goto badsub */
                    break 'varname;
                }

                st.out.push(cc as u8);
            } else {
                badsub = true; /* goto badsub */
                break 'varname;
            }
            break 'varname;
        }

        if badsub {
            /* badsub: */
            pungetc();
        } else if subtype == 0 {
            let cc = st.c;

            if st.chkeofmark != 0 {
                st.out.push(st.c as u8);
            }

            if st.c == '%' as c_int || st.c == '#' as c_int {
                subtype = if st.c == '#' as c_int {
                    VSTRIMLEFT
                } else {
                    VSTRIMRIGHT
                };
                st.c = pgetc_eatbnl();
                if st.c == cc {
                    if st.chkeofmark != 0 {
                        st.out.push(st.c as u8);
                    }
                    subtype += 1;
                } else {
                    pungetc();
                }

                newsyn = BASESYNTAX();
            } else {
                if st.c == ':' as c_int {
                    subtype = VSNUL;
                    st.c = pgetc_eatbnl();
                    if st.chkeofmark != 0 {
                        st.out.push(st.c as u8);
                    }
                    /*FALLTHROUGH*/
                }
                /* default: */
                /* The search runs over the whole array, terminator
                 * included, because that is what `strchr` does: a NUL
                 * `c` lands on index 5 rather than missing. */
                if let Some(at) = types.iter().position(|&b| b as c_int == st.c) {
                    subtype |= at as c_int + VSNORMAL;
                }
            }
        } else {
            if subtype == VSLENGTH && st.c != '}' as c_int {
                subtype = 0;
            }
            /* badsub: */
            pungetc();
        }

        if newsyn == ARISYNTAX() {
            newsyn = DQSYNTAX();
        }

        if (newsyn != st.syn().syntax || st.syn().innerdq != 0) && subtype != VSNORMAL {
            synstack_ops::push(&mut st.synstack, newsyn);

            st.syn_mut().varpushed += 1;
            st.syn_mut().dblquote = (newsyn != BASESYNTAX()) as c_int;
        }

        if subtype != VSNORMAL {
            st.syn_mut().varnest += 1;
            if st.syn().dblquote != 0 {
                st.syn_mut().dqvarnest += 1;
            }
        }
        if st.chkeofmark == 0 {
            st.out[typeloc - 1] = CTLVAR as u8;
            st.out[typeloc] = (subtype | VSBIT) as u8;
            st.out.push(b'=');
        }
    } else {
        pungetc();
    }

    /* goto parsesub_return; */
    false
}

/*
 * Called to parse command substitutions.  oldstyle is set if the command
 * is enclosed inside `...` rather than $(...).
 */

/* parsebackq: */
unsafe fn parsebackq(st: &mut Rt1<'_>, oldstyle: c_int) {
    let mut saveprompt: c_int = 0;
    let saveheredoclist: Vec<heredoc>;
    let nlpp: usize;
    let n: Option<Node>;
    let mut ml: c_uint;
    /* `grabstackstr(pout)` had to reserve the backquote's text because
     * `list(2)` builds on the same stack; owning it says the same thing, and
     * it has to outlive the `popfile` below because `setinputstring` reads
     * through the pointer rather than copying. */
    let mut pstr: BString = BString::new(Vec::new());
    let str: BString;

    if st.chkeofmark != 0 {
        synstack_ops::push(&mut st.synstack, BASESYNTAX());
        st.syn_mut().backq = oldstyle + 1;
        st.printesc = true;
        /* goto parsebackq_out; */
        if oldstyle != 0 {
            tokpushback = 0;
        }
        return;
    }
    /* `STADJUST(oldstyle - 1, out)` drops the '(' of `$(` and leaves the '`'
     * of a backquote in place; either way the last byte becomes CTLBACKQ. */
    if oldstyle == 0 {
        st.out.pop();
    }
    let last = st.out.len() - 1;
    st.out[last] = CTLBACKQ as u8;
    /* The word so far is parked while `list(2)` runs, which is what
     * `grabstackblock(savelen)` bought the C. */
    str = mem::take(&mut st.out);
    if oldstyle != 0 {
        /* We must read until the closing backquote, giving special
        treatment to some slashes, and then push the string and
        reread it as input, interpreting it normally.  */
        let mut done = false;
        let mut pc: c_int;

        while !done {
            'bqbody: {
                if needprompt != 0 {
                    setprompt(2);
                }
                pc = pgetc_eatbnl();
                if pc == '`' as c_int {
                    done = true;
                } else if pc == '\\' as c_int {
                    pc = pgetc();
                    if pc != '\\' as c_int
                        && pc != '`' as c_int
                        && pc != '$' as c_int
                        && (st.syn().dblquote == 0 || pc != '"' as c_int)
                    {
                        pstr.push(b'\\');
                    }
                    ml = getmbc_at(&mut pstr, pc, 2);
                    let grown = pstr.len() + ml as usize;
                    pstr.set_len(grown);
                    if ml != 0 {
                        break 'bqbody; /* continue */
                    }
                } else if pc == PEOF {
                    synerror(c"EOF in backquote substitution".as_ptr());
                } else if pc == '\n' as c_int {
                    nlnoprompt();
                }
                pstr.push(pc as u8);
            }
        }
        /* `pout[-1] = '\0'` — over the closing backquote the loop just
         * wrote, which is why the buffer is never empty here. */
        let last = pstr.len() - 1;
        pstr[last] = 0;
        setinputstring(pstr.as_mut_ptr() as *mut c_char);
    }
    /* The C walks to the tail of `bqlist` and appends an empty cell, then
     * fills its `n` after the recursive parse.  Reserving the slot first is
     * the same order; nothing else can append to this list while `list(2)`
     * runs, because `bqlist` is a local of *this* `readtoken1`. */
    nlpp = st.bqlist.len();
    st.bqlist.push(None);

    saveheredoclist = takeglobal(addr_of_mut!(heredoclist));

    if oldstyle != 0 {
        saveprompt = doprompt;
        doprompt = 0;
    }

    n = list(2).into_node();

    if oldstyle != 0 {
        doprompt = saveprompt;
    } else {
        if readtoken() != TRP {
            synexpect(TRP);
        }
        setinputstring(ptr::addr_of!(crate::mystring::nullstr) as *const c_char as *mut c_char);
    }

    parseheredoc();
    heredoclist = saveheredoclist;

    st.bqlist[nlpp] = n;
    /* Start reading from old file again. */
    popfile();

    st.out = str;

    /* parsebackq_out: */
    if oldstyle != 0 {
        /* Ignore any pushed back tokens left from the backquote
         * parsing.
         */
        tokpushback = 0;
    }
}

/*
 * Parse an arithmetic expansion (indicate start of one and set state)
 */
/* parsearith: */
unsafe fn parsearith(st: &mut Rt1<'_>) {
    synstack_ops::push(&mut st.synstack, ARISYNTAX());
    st.syn_mut().dblquote = 1;
    if st.chkeofmark != 0 {
        st.out.push(st.c as u8);
    } else {
        /* `STADJUST(-1); out[-1] = CTLARI` — drop the second '(' of `$((`
         * and relabel the '$'. */
        st.out.pop();
        let last = st.out.len() - 1;
        st.out[last] = CTLARI as u8;
    }
    /* goto parsearith_return; */
}

/*
 * Return of a legal variable name (a letter or underscore followed by zero or
 * more letters, underscores, and digits).
 */

// [spec:dash:def:parser.endofname-fn]
// [spec:dash:sem:parser.endofname-fn]
pub unsafe fn endofname(name: *const c_char) -> *mut c_char {
    let mut p: *mut c_char;

    p = name as *mut c_char;
    if !is_name(*p as c_int) {
        return p;
    }
    loop {
        p = p.offset(1);
        if *p == 0 {
            break;
        }
        if !is_in_name(*p as c_int) {
            break;
        }
    }
    p
}

/*
 * Called when an unexpected token is read during the parse.  The argument
 * is the token that is expected, or -1 if more than one type of token can
 * occur at this point.
 */

// [spec:dash:def:parser.synexpect-fn]
// [spec:dash:sem:parser.synexpect-fn]
unsafe fn synexpect(token: c_int) -> ! {
    let mut msg: [c_char; 64] = [0; 64];
    let mut message = Vec::new();

    message.extend_from_slice(CStr::from_ptr(tokname.0[lasttoken as usize]).to_bytes());
    message.extend_from_slice(b" unexpected");
    if token >= 0 {
        message.extend_from_slice(b" (expecting ");
        message.extend_from_slice(CStr::from_ptr(tokname.0[token as usize]).to_bytes());
        message.push(b')');
    }
    let copied = message.len().min(msg.len() - 1);
    core::ptr::copy_nonoverlapping(message.as_ptr(), msg.as_mut_ptr() as *mut u8, copied);
    synerror(msg.as_ptr());
    /* NOTREACHED */
}

// [spec:dash:def:parser.synerror-fn]
// [spec:dash:sem:parser.synerror-fn]
#[allow(unreachable_code)]
unsafe fn synerror(msg: *const c_char) -> ! {
    errlinno = crate::plinno!();
    let mut message = b"Syntax error: ".to_vec();
    message.extend_from_slice(CStr::from_ptr(msg).to_bytes());
    crate::error::sh_error(&message);
    /* NOTREACHED */
    unreachable!()
}

// [spec:dash:def:parser.setprompt-fn]
// [spec:dash:sem:parser.setprompt-fn]
#[inline(never)]
unsafe fn setprompt(which: c_int) {
    let show: c_int;

    needprompt = 0;
    whichprompt = which;

    /* #ifdef SMALL: show = 1 */
    show = (!crate::histedit::editing_active()) as c_int;
    if show != 0 && crate::input::cur_pf().nleft == 0 {
        /* `pushstackmark(&smark, stackblocksize())` bounded the prompt
         * `expandstr` had left in the region for `out2str` to read.  The
         * expansion buffer is owned, so there is nothing to bound. */
        let prompt = CStr::from_ptr(getprompt(ptr::null_mut())).to_bytes();
        let _ = (*crate::output::stderr()).write_all(prompt);
    }
}

// [spec:dash:def:parser.expandstr-fn]
// [spec:dash:sem:parser.expandstr-fn]
pub unsafe fn expandstr(ps: *const c_char) -> *const c_char {
    let file_stop: usize;
    let savehandler: *mut jmploc;
    let saveheredoclist: Vec<heredoc>;
    let mut result: *const c_char;
    let saveprompt: c_int;
    let mut jmploc: crate::error::jmploc = crate::error::jmploc::new();
    let err: c_int;

    file_stop = crate::input::cur_mark();

    /* XXX Fix (char *) cast. */
    setinputstring(ps as *mut c_char);

    saveheredoclist = takeglobal(addr_of_mut!(heredoclist));
    saveprompt = doprompt;
    doprompt = 0;
    needprompt = 0;
    result = ps;
    savehandler = handler;
    /* `if (unlikely(err = setjmp(jmploc.loc))) goto out;` — handlers in
     * this port are established by `eval::setjmp_catch`, not a real
     * `setjmp`, so the body goes in the closure and everything after the
     * call is the `out:` label. Raw pointers rather than captures keep
     * the C's aliasing (the closure writes locals the tail then reads).
     * The C's `union node n` is a bare local it never reads after the
     * call, so it lives inside the closure here. */
    let jl: *mut crate::error::jmploc = addr_of_mut!(jmploc);
    let resultp: *mut *const c_char = addr_of_mut!(result);
    err = crate::eval::setjmp_catch(jl, || unsafe {
        handler = jl;

        readtoken1(pgetc_eatbnl(), DQSYNTAX(), EofMark::Fake, 0);

        let n = Node::Arg(narg {
            text: wordtext_node(),
            backquote: takeglobal(addr_of_mut!(backquotelist)),
        });

        expandarg(&n, None, EXP_QUOTED);
        /* The C reads the expansion back as `stackblock()`; the expansion
         * buffer is owned now, so the read is named.  The C's pointer was
         * live only until the next `stalloc`; this one is live until the
         * next expansion, which is a superset. */
        *resultp = crate::expand::expansion_result() as *const c_char;
    });

    /* out: */
    restore_handler_expandarg(savehandler, err);

    doprompt = saveprompt;
    unwindfiles(file_stop);
    heredoclist = saveheredoclist;

    result
}

/*
 * called by editline -- any expansions to the prompt
 *    should be added here.
 */

// [spec:dash:def:parser.getprompt-fn]
// [spec:dash:sem:parser.getprompt-fn]
pub unsafe fn getprompt(unused: *mut c_void) -> *const c_char {
    let prompt: *const c_char;

    match whichprompt {
        1 => {
            prompt = crate::var::ps1val();
        }
        2 => {
            prompt = crate::var::ps2val();
        }
        /* default: falls into case 0 outside DEBUG builds */
        _ => {
            return ptr::addr_of!(crate::mystring::nullstr) as *const c_char;
        }
    }

    expandstr(prompt)
}

/// The C reaches `parsekwd` through `mystring.c`'s `findstring`, a generic
/// `bsearch` over an array of `char *`. This is that function's only
/// instantiation in the port, and `strcmp` over the table is plain byte
/// order — `parsekwd` is ASCII and sorted — so `<[u8]>::cmp` is the C
/// comparator rather than an approximation of it.
///
/// The result stays a pointer *into* `parsekwd` because `readtoken1`
/// recovers the token code by subtracting the base.
// [spec:dash:def:parser.findkwd-fn]
// [spec:dash:sem:parser.findkwd-fn]
pub unsafe fn findkwd(s: *const c_char) -> *const *const c_char {
    let key = core::ffi::CStr::from_ptr(s).to_bytes();
    match parsekwd
        .0
        .binary_search_by(|&kwd| core::ffi::CStr::from_ptr(kwd).to_bytes().cmp(key))
    {
        Ok(i) => parsekwd.0.as_ptr().add(i),
        Err(_) => ptr::null(),
    }
}

